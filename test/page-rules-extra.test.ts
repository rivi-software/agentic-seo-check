import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import { auditHtml } from "../src/core/audit.js";
import type { Finding, RedirectHop, ResponseInfo } from "../src/core/types.js";
import { incompleteEdits, unquotedEdits, withoutFix } from "./helpers/fixes.js";

/** The page rules this file covers: framework defaults, canonical spellings, language, LCP, video and redirects. */
const RULES = [
  "meta-description.generic",
  "canonical.noindex-conflict",
  "canonical.fragment",
  "canonical.tracking-parameters",
  "hreflang.lang-mismatch",
  "img.lcp-fetchpriority-missing",
  "structured-data.video-missing",
  "response.temporary-redirect",
];

const PAGE = "https://www.example.com/widgets/blue/";

const fixture = (name: string): string =>
  readFileSync(new URL(`fixtures/${name}`, import.meta.url), "utf-8");

const doc = (head: string, body = "<p>Text</p>", lang = "en") =>
  `<!doctype html><html lang="${lang}"><head><meta charset="utf-8"><title>Blue widgets for every workshop | Acme</title>${head}</head><body><h1>Blue widgets</h1><a href="/">Home</a>${body}</body></html>`;

const response = (
  url: string,
  options: { headers?: Record<string, string>; chain?: RedirectHop[] } = {}
): ResponseInfo => ({
  status: 200,
  finalUrl: url,
  redirectChain: options.chain ?? [],
  timeMs: 50,
  contentType: "text/html; charset=utf-8",
  headers: options.headers ?? {},
});

/**
 * The findings of the rules above on `html`, each with a complete fix that quotes the page as
 * written.
 */
const audit = async (
  html: string,
  options: {
    url?: string;
    headers?: Record<string, string>;
    chain?: RedirectHop[];
  } = {}
): Promise<Finding[]> => {
  const url = options.url ?? PAGE;

  const result = await auditHtml(
    html,
    { url, source: "url", response: response(url, options) },
    { onlyRules: RULES }
  );

  // Response edits name the redirecting URL's answer, not this page's HTML.
  const htmlFindings = result.findings.filter(
    (f) => !f.rule.startsWith("response.")
  );

  expect(withoutFix(result.findings)).toStrictEqual([]);
  expect(unquotedEdits(htmlFindings, html)).toStrictEqual([]);
  expect(incompleteEdits(result.findings)).toStrictEqual([]);

  return result.findings;
};

const rulesOf = (findings: Finding[]) => findings.map((f) => f.rule);

const fixOf = (findings: Finding[], rule: string) =>
  findings.find((f) => f.rule === rule)?.fix;

describe("the added page rules on the fixtures", () => {
  it.each([
    ["good-page.html", PAGE],
    ["aeo-good-page.html", "https://www.example.com/guides/blue-widgets/"],
  ])("stay quiet on %s", async (name, url) => {
    expect(rulesOf(await audit(fixture(name), { url }))).toStrictEqual([]);
  });
});

describe("meta-description.generic", () => {
  it.each([
    "Web site created using create-react-app",
    "Generated by create next app",
    "Welcome to Remix!",
    "Write an awesome description for your new site here. You can edit this line in _config.yml.",
  ])("fires on %j and rewrites the tag", async (description) => {
    const html = doc(`<meta name="description" content="${description}">`);
    const findings = await audit(html);

    expect(rulesOf(findings)).toStrictEqual(["meta-description.generic"]);
    expect(fixOf(findings, "meta-description.generic")).toMatchObject([
      {
        action: "replace",
        current: `<meta name="description" content="${description}">`,
        code: '<meta name="description" content="{{page description}}">',
      },
    ]);
  });

  it("stays quiet on a description that only mentions a framework", async () => {
    const html = doc(
      '<meta name="description" content="How we moved our shop from create-react-app to Next.js, and what it did to our load times.">'
    );

    expect(rulesOf(await audit(html))).toStrictEqual([]);
  });
});

describe("canonical.noindex-conflict", () => {
  it("removes the canonical of a noindex page that names another URL", async () => {
    const tag =
      '<link rel="canonical" href="https://www.example.com/widgets/">';

    const findings = await audit(
      doc(`<meta name="robots" content="noindex">${tag}`)
    );

    expect(rulesOf(findings)).toStrictEqual(["canonical.noindex-conflict"]);
    expect(fixOf(findings, "canonical.noindex-conflict")).toMatchObject([
      { action: "remove", current: tag },
    ]);
  });

  it("reads noindex from the X-Robots-Tag header", async () => {
    const findings = await audit(
      doc('<link rel="canonical" href="https://www.example.com/widgets/">'),
      { headers: { "x-robots-tag": "noindex" } }
    );

    expect(rulesOf(findings)).toStrictEqual(["canonical.noindex-conflict"]);
  });

  it("stays quiet on a noindex page with a self-referencing canonical, and on an indexable copy", async () => {
    expect(
      rulesOf(
        await audit(
          doc(
            `<meta name="robots" content="noindex"><link rel="canonical" href="${PAGE}">`
          )
        )
      )
    ).toStrictEqual([]);
    expect(
      rulesOf(
        await audit(
          doc('<link rel="canonical" href="https://www.example.com/widgets/">')
        )
      )
    ).toStrictEqual([]);
  });
});

describe("canonical.fragment", () => {
  it("drops the fragment from the canonical", async () => {
    const findings = await audit(
      doc(`<link rel="canonical" href="${PAGE}#reviews">`)
    );

    expect(rulesOf(findings)).toStrictEqual(["canonical.fragment"]);
    expect(fixOf(findings, "canonical.fragment")).toMatchObject([
      { code: `<link rel="canonical" href="${PAGE}">` },
    ]);
  });

  it("stays quiet on a hash route and on an empty fragment", async () => {
    expect(
      rulesOf(
        await audit(
          doc('<link rel="canonical" href="https://www.example.com/#/widgets">')
        )
      )
    ).toStrictEqual([]);
    expect(
      rulesOf(await audit(doc(`<link rel="canonical" href="${PAGE}#">`)))
    ).toStrictEqual([]);
  });
});

describe("canonical.tracking-parameters", () => {
  it("drops the tracking parameters and keeps the others", async () => {
    const findings = await audit(
      doc(
        `<link rel="canonical" href="${PAGE}?color=blue&amp;utm_source=news&amp;gclid=abc">`
      )
    );

    expect(rulesOf(findings)).toStrictEqual(["canonical.tracking-parameters"]);
    expect(
      findings.find((f) => f.rule === "canonical.tracking-parameters")
    ).toMatchObject({
      severity: "warning",
      evidence: { parameters: ["utm_source", "gclid"] },
      fix: [{ code: `<link rel="canonical" href="${PAGE}?color=blue">` }],
    });
  });

  it("stays quiet on parameters that change the content", async () => {
    expect(
      rulesOf(
        await audit(
          doc(`<link rel="canonical" href="${PAGE}?color=blue&amp;page=2">`)
        )
      )
    ).toStrictEqual([]);
  });
});

/** An hreflang set where this page is `own`. */
const hreflangSet = (own: string) =>
  `<link rel="alternate" hreflang="${own}" href="${PAGE}"><link rel="alternate" hreflang="de" href="https://www.example.com/de/widgets/blau/"><link rel="alternate" hreflang="x-default" href="${PAGE}">`;

describe("hreflang.lang-mismatch", () => {
  it("sets <html lang> to the page's own hreflang entry, on condition", async () => {
    const html = doc(hreflangSet("nl"), "<p>Tekst</p>", "en");
    const findings = await audit(html);

    expect(rulesOf(findings)).toStrictEqual(["hreflang.lang-mismatch"]);
    expect(fixOf(findings, "hreflang.lang-mismatch")).toMatchObject([
      { current: '<html lang="en">', code: '<html lang="nl">' },
    ]);
  });

  it("stays quiet when only the region differs, or one of several own entries matches", async () => {
    expect(
      rulesOf(await audit(doc(hreflangSet("en-gb"), "<p>Text</p>", "en-US")))
    ).toStrictEqual([]);
    expect(
      rulesOf(
        await audit(
          doc(
            `${hreflangSet("en-us")}<link rel="alternate" hreflang="en-gb" href="${PAGE}">`,
            "<p>Text</p>",
            "en"
          )
        )
      )
    ).toStrictEqual([]);
  });
});

describe("img.lcp-fetchpriority-missing", () => {
  const hero =
    '<img src="/img/hero.jpg" width="1200" height="600" alt="A blue widget">';

  it("adds fetchpriority=high to the first large image", async () => {
    const findings = await audit(doc("", hero));

    expect(rulesOf(findings)).toStrictEqual(["img.lcp-fetchpriority-missing"]);
    expect(fixOf(findings, "img.lcp-fetchpriority-missing")).toMatchObject([
      {
        current: hero,
        code: '<img src="/img/hero.jpg" width="1200" height="600" alt="A blue widget" fetchpriority="high">',
      },
    ]);
  });

  it("reads a responsive image without a width as large", async () => {
    expect(
      rulesOf(
        await audit(
          doc(
            "",
            '<img src="/img/hero.jpg" srcset="/img/hero-800.jpg 800w, /img/hero-1600.jpg 1600w" alt="A blue widget">'
          )
        )
      )
    ).toStrictEqual(["img.lcp-fetchpriority-missing"]);
  });

  it.each([
    [
      "another image already has high priority",
      `<img src="/a.jpg" width="800" height="400" alt="A" fetchpriority="high">${hero}`,
    ],
    [
      "the image sets a priority of its own",
      '<img src="/img/hero.jpg" width="1200" height="600" alt="A" fetchpriority="low">',
    ],
    [
      "the image is lazy (img.lazy-above-fold's case)",
      '<img src="/img/hero.jpg" width="1200" height="600" alt="A" loading="lazy">',
    ],
    ["the image has no size or srcset", '<img src="/img/logo.png" alt="Acme">'],
    [
      "the image is small",
      '<img src="/img/badge.jpg" width="120" height="60" alt="Badge">',
    ],
    ["the image is far down the page", `<p>${"word ".repeat(150)}</p>${hero}`],
  ])("stays quiet when %s", async (_, body) => {
    expect(rulesOf(await audit(doc("", body)))).toStrictEqual([]);
  });
});

describe("structured-data.video-missing", () => {
  it("adds VideoObject JSON-LD with the YouTube player and its thumbnail", async () => {
    const findings = await audit(
      doc(
        "",
        '<main><iframe src="https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ" title="Assembly"></iframe></main>'
      )
    );

    expect(rulesOf(findings)).toStrictEqual(["structured-data.video-missing"]);

    const [edit] = fixOf(findings, "structured-data.video-missing") ?? [];

    expect(edit?.code).toContain(
      '"embedUrl": "https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ"'
    );
    expect(edit?.code).toContain(
      '"thumbnailUrl": "https://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg"'
    );
  });

  it("reads a <video> with controls, its source and its poster", async () => {
    const findings = await audit(
      doc(
        "",
        '<video controls poster="/img/poster.jpg"><source src="/media/assembly.mp4" type="video/mp4"></video>'
      )
    );

    const [edit] = fixOf(findings, "structured-data.video-missing") ?? [];

    expect(edit?.code).toContain(
      '"contentUrl": "https://www.example.com/media/assembly.mp4"'
    );
    expect(edit?.code).toContain(
      '"thumbnailUrl": "https://www.example.com/img/poster.jpg"'
    );
  });

  it.each([
    [
      "the page has a VideoObject, nested in an Article",
      '<script type="application/ld+json">{"@context":"https://schema.org","@type":"Article","headline":"Blue widgets","video":{"@type":"VideoObject","name":"Assembly"}}</script>',
      '<iframe src="https://player.vimeo.com/video/123456"></iframe>',
    ],
    [
      "the video is an animation without controls that a script starts",
      "",
      '<video src="/media/hero.mp4" muted playsinline preload="metadata"></video>',
    ],
    [
      "the video is a background that plays by itself",
      "",
      '<video autoplay muted loop playsinline src="/media/waves.mp4"></video>',
    ],
    [
      "the video is in the footer",
      "",
      '<footer><iframe src="https://www.youtube.com/embed/dQw4w9WgXcQ"></iframe></footer>',
    ],
    [
      "the iframe is a map, not a video",
      "",
      '<iframe src="https://www.google.com/maps/embed?pb=1"></iframe>',
    ],
  ])("stays quiet when %s", async (_, head, body) => {
    expect(rulesOf(await audit(doc(head, body)))).toStrictEqual([]);
  });
});

describe("response.temporary-redirect", () => {
  it("asks for a permanent redirect where a 302 only moves to https", async () => {
    const findings = await audit(doc(""), {
      chain: [{ url: "http://www.example.com/widgets/blue/", status: 302 }],
    });

    expect(rulesOf(findings)).toStrictEqual(["response.temporary-redirect"]);
    expect(fixOf(findings, "response.temporary-redirect")).toMatchObject([
      {
        in: "http",
        url: "http://www.example.com/widgets/blue/",
        current: `HTTP/1.1 302 Found\nLocation: ${PAGE}`,
        code: `HTTP/1.1 301 Moved Permanently\nLocation: ${PAGE}`,
      },
    ]);
  });

  it("keeps the method of a 307 with a 308, for a trailing slash", async () => {
    const findings = await audit(doc(""), {
      chain: [{ url: "https://www.example.com/widgets/blue", status: 307 }],
    });

    expect(fixOf(findings, "response.temporary-redirect")?.[0]?.code).toBe(
      `HTTP/1.1 308 Permanent Redirect\nLocation: ${PAGE}`
    );
  });

  it("stays quiet on a permanent redirect and on a temporary one to another page", async () => {
    expect(
      rulesOf(
        await audit(doc(""), {
          chain: [{ url: "http://www.example.com/widgets/blue/", status: 301 }],
        })
      )
    ).toStrictEqual([]);
    expect(
      rulesOf(
        await audit(doc(""), {
          chain: [{ url: "https://www.example.com/", status: 302 }],
        })
      )
    ).toStrictEqual([]);
  });
});
